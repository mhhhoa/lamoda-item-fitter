/** Размеры PNG читаем из заголовка файла — чтобы не искажать пропорции. */
function pngSize(file) {
  const head = fs.readFileSync(file).subarray(16, 24);
  return { width: head.readUInt32BE(0), height: head.readUInt32BE(4) };
}

function shot(name, maxWidth = 640) {
  const file = path.join(SCREENS, name);
  const { width, height } = pngSize(file);
  const scale = Math.min(1, maxWidth / width);
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 140, after: 200 },
    children: [new ImageRun({
      type: "png",
      data: fs.readFileSync(file),
      transformation: { width: Math.round(width * scale), height: Math.round(height * scale) },
    })],
  });
}

