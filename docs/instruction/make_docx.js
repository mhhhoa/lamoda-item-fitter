/** Абзац из кусочков: строка или {b: "жирным"} / {c: "моноширинным"}. */
function p(parts, options = {}) {
  const list = Array.isArray(parts) ? parts : [parts];
  return new Paragraph({
    spacing: { after: options.after ?? 120 },
    alignment: options.align,
    children: list.map((part) => {
      if (typeof part === "string") return new TextRun({ text: part, size: 22 });
      if (part.b !== undefined) return new TextRun({ text: part.b, bold: true, size: 22 });
      if (part.c !== undefined) {
        return new TextRun({ text: part.c, font: "Consolas", size: 20, color: "1F4E79" });
      }
      return new TextRun({ text: part.i, italics: true, size: 22, color: MUTED });
    }),
  });
}

const bullet = (parts) => {
  const paragraph = p(parts, { after: 60 });
  paragraph.root.push();
  return new Paragraph({
    numbering: { reference: "dots", level: 0 },
    spacing: { after: 60 },
    children: paragraph.root.filter((node) => node instanceof TextRun),
  });
};

const step = (parts) => new Paragraph({
  numbering: { reference: "steps", level: 0 },
  spacing: { after: 80 },
  children: p(parts).root.filter((node) => node instanceof TextRun),
});

/** Врезка на светлой плашке — для того, что нельзя пропустить. */
function callout(title, lines) {
  const children = [new Paragraph({
    spacing: { after: 80 },
    children: [new TextRun({ text: title, bold: true, size: 22, color: ACCENT })],
  })];
  for (const line of lines) children.push(p(line, { after: 40 }));
  return new Table({
    columnWidths: [CONTENT_DXA],
    width: { size: CONTENT_DXA, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      left: { style: BorderStyle.SINGLE, size: 18, color: ACCENT },
      right: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      insideHorizontal: { style: BorderStyle.NONE },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [new TableRow({
      children: [new TableCell({
        width: { size: CONTENT_DXA, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: "F5F8FC" },
        margins: { top: 160, bottom: 160, left: 200, right: 200 },
        children,
      })],
    })],
  });
}

/** Таблица «слева коротко — справа объяснение». */
function table(headers, rows, widths) {
  const cell = (parts, width, options = {}) => new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: options.head ? { type: ShadingType.CLEAR, fill: HEAD_FILL } : undefined,
    margins: { top: 90, bottom: 90, left: 140, right: 140 },
    children: [p(parts, { after: 0 })],
  });

  return new Table({
    columnWidths: widths,
    width: { size: CONTENT_DXA, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      left: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      right: { style: BorderStyle.SINGLE, size: 4, color: "C9D3E4" },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: "DDE3EC" },
      insideVertical: { style: BorderStyle.SINGLE, size: 2, color: "DDE3EC" },
    },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((title, i) => cell([{ b: title }], widths[i], { head: true })),
      }),
      ...rows.map((row) => new TableRow({
        children: row.map((parts, i) => cell(parts, widths[i])),
      })),
    ],
  });
}

